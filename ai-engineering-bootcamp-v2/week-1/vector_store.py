"""Pinecone vector-store configuration and connection helpers (Session 2 RAG).

This module only connects to an EXISTING Pinecone index and validates that it fits
our embeddings. It never creates, replaces or deletes an index.

Embeddings are generated by this backend with OpenAI text-embedding-3-small
(1536 dimensions), so the index must be a plain dense index with
dimension 1536 and metric "cosine" (not an integrated-embedding index).

Connectivity check (no OpenAI call, no tokens spent):
    python vector_store.py
"""

from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from dotenv import load_dotenv
from pinecone import NotFoundError, Pinecone
from pinecone.models.indexes.schema import (
    DenseVectorField,
    SemanticTextField,
    StringField,
)

# Same approach as main.py: load .env from this folder, regardless of the shell's
# working directory. On Render there is no .env; the variables come from the
# service's Environment settings, and load_dotenv simply does nothing.
_ENV_PATH = Path(__file__).resolve().parent / ".env"
load_dotenv(_ENV_PATH)

EMBEDDING_MODEL = "text-embedding-3-small"
EMBEDDING_DIMENSIONS = 1536
REQUIRED_METRIC = "cosine"

# Variable names only. Values are never logged or returned.
_REQUIRED_ENV_VARS = ("OPENAI_API_KEY", "PINECONE_API_KEY", "PINECONE_INDEX_NAME")
_SECRET_ENV_VARS = ("OPENAI_API_KEY", "PINECONE_API_KEY")


class VectorStoreError(RuntimeError):
    """Raised when the vector store is misconfigured, unreachable or incompatible."""


@dataclass(frozen=True)
class VectorStoreConfig:
    """Non-secret settings. API keys are deliberately not stored here."""

    index_name: str
    namespace: str | None  # None = Pinecone's default namespace
    embedding_model: str = EMBEDDING_MODEL
    embedding_dimensions: int = EMBEDDING_DIMENSIONS
    metric: str = REQUIRED_METRIC


def _env(name: str) -> str | None:
    """Read an env var, treating empty or whitespace-only values as unset."""

    value = os.getenv(name)
    if value is None or not value.strip():
        return None
    return value.strip()


def load_config() -> VectorStoreConfig:
    """Read settings from the environment; fail with the names of missing variables."""

    missing = [name for name in _REQUIRED_ENV_VARS if _env(name) is None]
    if missing:
        raise VectorStoreError(
            "Missing required environment variable(s): "
            + ", ".join(missing)
            + f". Set them in {_ENV_PATH} locally or in the Render service environment."
        )
    return VectorStoreConfig(
        index_name=_env("PINECONE_INDEX_NAME"),  # type: ignore[arg-type]
        namespace=_env("PINECONE_NAMESPACE"),
    )


def _redact(text: str) -> str:
    """Defensive: strip any secret values that might appear in an error message."""

    for name in _SECRET_ENV_VARS:
        secret = _env(name)
        if secret:
            text = text.replace(secret, f"<{name} redacted>")
    return text


_client: Pinecone | None = None
_index_host: str | None = None


def get_pinecone_client() -> Pinecone:
    """One shared client, created on first use (reads PINECONE_API_KEY explicitly)."""

    global _client
    if _client is None:
        load_config()  # fail early with a clear message if variables are missing
        _client = Pinecone(api_key=_env("PINECONE_API_KEY"))
    return _client


def describe_and_validate_index(config: VectorStoreConfig | None = None) -> dict[str, Any]:
    """
    Look up the existing index and check it matches our embeddings.

    Returns a dict of non-secret index facts. Raises VectorStoreError if the index
    does not exist, is not ready, or has the wrong shape (dimension / metric / type).
    """

    config = config or load_config()
    pc = get_pinecone_client()

    try:
        model = pc.indexes.describe(config.index_name)
    except NotFoundError:
        raise VectorStoreError(
            f"Pinecone index '{config.index_name}' was not found in this project. "
            f"Create it in the Pinecone console (dense, dimension {EMBEDDING_DIMENSIONS}, "
            f"metric {REQUIRED_METRIC}) or fix PINECONE_INDEX_NAME. "
            "This service does not create indexes automatically."
        ) from None
    except Exception as exc:  # auth errors, network errors, ...
        raise VectorStoreError(
            f"Could not reach Pinecone to describe index '{config.index_name}': "
            f"{type(exc).__name__}: {_redact(str(exc))}"
        ) from None

    fields = model.schema.fields
    dense = {name: f for name, f in fields.items() if isinstance(f, DenseVectorField)}
    integrated = [
        name
        for name, f in fields.items()
        if isinstance(f, SemanticTextField)
        or (isinstance(f, StringField) and f.embed is not None)
    ]

    if integrated:
        raise VectorStoreError(
            f"Index '{config.index_name}' uses Pinecone integrated embedding "
            f"(field(s): {', '.join(sorted(integrated))}). This backend sends its own "
            f"{EMBEDDING_MODEL} vectors, so it needs a plain dense index with "
            f"dimension {EMBEDDING_DIMENSIONS} and metric {REQUIRED_METRIC}."
        )
    if len(dense) != 1:
        found = ", ".join(sorted(dense)) or "none"
        raise VectorStoreError(
            f"Index '{config.index_name}' must have exactly one dense vector field; "
            f"found {len(dense)} ({found})."
        )

    field_name, field = next(iter(dense.items()))
    problems = []
    if field.dimension != EMBEDDING_DIMENSIONS:
        problems.append(
            f"dimension is {field.dimension}, expected {EMBEDDING_DIMENSIONS} "
            f"for {EMBEDDING_MODEL}"
        )
    if (field.metric or "").lower() != REQUIRED_METRIC:
        problems.append(f"metric is '{field.metric}', expected '{REQUIRED_METRIC}'")
    if problems:
        raise VectorStoreError(
            f"Index '{config.index_name}' is incompatible: "
            + "; ".join(problems)
            + ". Dimension and metric cannot be changed on an existing index; "
            "create a new index with the right settings and point PINECONE_INDEX_NAME at it."
        )

    if not model.status.ready or not model.host:
        raise VectorStoreError(
            f"Index '{config.index_name}' exists but is not ready "
            f"(state: {model.status.state}). Try again in a minute."
        )

    deployment = model.deployment
    return {
        "index_name": model.name,
        "host": model.host,
        "ready": model.status.ready,
        "state": model.status.state,
        "deployment": type(deployment).__name__.replace("Deployment", "").lower(),
        "cloud": getattr(deployment, "cloud", None),
        "region": getattr(deployment, "region", None),
        "vector_field": field_name,
        "dimension": field.dimension,
        "metric": field.metric,
        "deletion_protection": model.deletion_protection,
    }


def get_index():
    """Data-plane handle for the validated index (used by /ingest and retrieval later)."""

    global _index_host
    if _index_host is None:
        _index_host = describe_and_validate_index()["host"]
    return get_pinecone_client().index(host=_index_host)


def check_connection() -> dict[str, Any]:
    """
    Health/debug check: config + index validation + vector counts.

    Makes two Pinecone calls (describe index, index stats) and no OpenAI calls.
    Never includes secret values; only reports whether keys are set.
    """

    config = load_config()
    index_info = describe_and_validate_index(config)

    try:
        stats = get_pinecone_client().index(host=index_info["host"]).describe_index_stats()
    except Exception as exc:
        raise VectorStoreError(
            f"Index described fine, but reading its stats failed: "
            f"{type(exc).__name__}: {_redact(str(exc))}"
        ) from None

    namespaces = {
        name: getattr(ns, "vector_count", None) for name, ns in (stats.namespaces or {}).items()
    }
    return {
        "status": "ok",
        "embedding_model": config.embedding_model,
        "embedding_dimensions": config.embedding_dimensions,
        "configured_namespace": config.namespace or "(default)",
        "openai_api_key_set": _env("OPENAI_API_KEY") is not None,
        "pinecone_api_key_set": _env("PINECONE_API_KEY") is not None,
        "index": index_info,
        "total_vector_count": stats.total_vector_count,
        "namespaces": namespaces,
    }


if __name__ == "__main__":
    try:
        result = check_connection()
    except VectorStoreError as exc:
        print(json.dumps({"status": "error", "error": str(exc)}, indent=2))
        sys.exit(1)
    print(json.dumps(result, indent=2, default=str))
